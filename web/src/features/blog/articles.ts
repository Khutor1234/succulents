/**
 * Статті блогу. Тексти — тут, у коді: їх небагато й вони змінюються рідко.
 * Нова стаття — новий об'єкт на початку списку (свіжі показуються першими).
 *
 * Тіло статті — список блоків:
 * - `p` — абзац; `h2` — підзаголовок; `ul` / `ol` — список;
 * - `tip` — виділена порада; `warning` — застереження; `recipe` — рецепт суміші з SOIL_RECIPES (у відсотках);
 * - `figure` — жива ілюстрація з поясненням (Illustrations.tsx).
 * У тексті **так** — жирний шрифт.
 */
export type Block =
  | { type: 'p'; text: string }
  | { type: 'h2'; text: string }
  | { type: 'ul' | 'ol'; items: string[] }
  | { type: 'tip'; text: string }
  | { type: 'recipe'; recipe: string }
  | { type: 'warning'; text: string }
  /** Жива ілюстрація з Illustrations.tsx (id — ключ у FIGURES) */
  | { type: 'figure'; id: FigureId }
  /** Кнопка «Знайти в магазині» — пошук за словом (напр. Graptoveria) */
  | { type: 'shop'; query: string }
  /** Перелік джерел наприкінці статті (зовнішні посилання) */
  | { type: 'sources'; items: { title: string; url: string }[] }

